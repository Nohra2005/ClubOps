"""Generate schemas/*.json and docs/capabilities.md from the capability registry.

python scripts/export_schemas.py           # write files
python scripts/export_schemas.py --check   # fail if the files are out of date (CI)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from clubops.capabilities.registry import CAPABILITIES, Control
from clubops.contracts.common import SCHEMA_VERSION, Result

ROOT = Path(__file__).resolve().parent.parent
SCHEMAS = ROOT / "schemas"
DOC = ROOT / "docs" / "capabilities.md"


def render_schemas() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for spec in CAPABILITIES:
        for side, model in (("request", spec.request), ("response", Result[spec.response])):  # type: ignore[name-defined]
            schema = model.model_json_schema()
            schema["$comment"] = f"clubops {SCHEMA_VERSION} · capability {spec.name} {spec.version} · generated"
            out[SCHEMAS / f"{spec.name}.{side}.json"] = json.dumps(schema, indent=2, sort_keys=True) + "\n"
    return out


def render_doc() -> str:
    lines = [
        "# Capabilities",
        "",
        "<!-- Generated by scripts/export_schemas.py from src/clubops/capabilities/registry.py. Do not edit. -->",
        "",
        f"Contract version **{SCHEMA_VERSION}**. Every capability returns `Result[<response>]` "
        "(see [contracts.md](contracts.md)). Full JSON Schemas are in [`schemas/`](../schemas).",
        "",
        "| Capability | Control | Stability | Request → Response | Timeout / retries | Fallback |",
        "|---|---|---|---|---|---|",
    ]
    for s in CAPABILITIES:
        lines.append(
            f"| `{s.name}` {s.version} | {s.control.value} | {s.stability.value} | "
            f"`{s.request.__name__}` → `{s.response.__name__}` | {s.policy.timeout_s:g}s / {s.policy.max_retries} | "
            f"{s.policy.fallback or '—'} |"
        )
    lines += [
        "",
        "## Permissions",
        "",
        "| Capability | May read | May propose actions | Cabinet only | Takes untrusted input |",
        "|---|---|---|---|---|",
    ]
    for s in CAPABILITIES:
        reads = ", ".join(f"`{r}`" for r in s.may_read) or "—"
        proposes = ", ".join(f"`{a.value}`" for a in s.may_propose) or "—"
        cabinet = "yes" if s.requires_cabinet else "no"
        untrusted = "yes" if s.takes_untrusted else "no"
        lines.append(f"| `{s.name}` | {reads} | {proposes} | {cabinet} | {untrusted} |")
    lines += ["", "## What each capability does", ""]
    for s in CAPABILITIES:
        lines.append(f"- **`{s.name}`** ({s.control.value}): {s.summary}")
    counts = {c: sum(1 for s in CAPABILITIES if s.control is c) for c in Control}
    lines += [
        "",
        f"Totals: {counts[Control.AGENTIC]} agentic, {counts[Control.DETERMINISTIC]} deterministic, "
        f"{counts[Control.HUMAN]} human-only.",
        "",
    ]
    return "\n".join(lines)


def main(check: bool) -> int:
    expected = {**render_schemas(), DOC: render_doc()}
    stale = [p for p, text in expected.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    orphans = [p for p in SCHEMAS.glob("*.json") if p not in expected]
    if check:
        for p in [*stale, *orphans]:
            print(f"out of date: {p.relative_to(ROOT)}")
        if stale or orphans:
            print("run: python scripts/export_schemas.py")
        return 1 if stale or orphans else 0
    SCHEMAS.mkdir(exist_ok=True)
    for p in orphans:
        p.unlink()
    for p, text in expected.items():
        p.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(expected)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
